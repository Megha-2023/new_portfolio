const profileLinkDefinitions = [
  { configKey: 'LINKEDIN_PROFILE_URL', labelKey: 'profileLinkedIn' },
  { configKey: 'GITHUB_PROFILE_URL', labelKey: 'profileGitHub' },
  { configKey: 'X_PROFILE_URL', labelKey: 'profileX' }
];

const safeExternalUrl = (configKey) => {
  const value = window.PORTFOLIO_CONFIG?.[configKey]?.trim();
  if (!value) return null;
  try {
    const url = new URL(value);
    return url.protocol === 'https:' || url.protocol === 'http:' ? url.href : null;
  } catch (_) {
    return null;
  }
};

const createExternalLink = ({ configKey, labelKey }) => {
  const href = safeExternalUrl(configKey);
  if (!href) return null;

  const link = document.createElement('a');
  link.href = href;
  link.target = '_blank';
  link.rel = 'noopener noreferrer';

  const label = document.createElement('span');
  label.dataset.i18n = labelKey;
  label.textContent = t(labelKey);
  link.append(label);

  const indicator = document.createElement('span');
  indicator.className = 'external-link-mark';
  indicator.setAttribute('aria-hidden', 'true');
  indicator.textContent = '↗';
  link.append(indicator);

  const accessibleNote = document.createElement('span');
  accessibleNote.className = 'sr-only';
  accessibleNote.dataset.i18n = 'opensNewWindow';
  accessibleNote.textContent = t('opensNewWindow');
  link.append(accessibleNote);
  return link;
};

const populateLinks = (container, definitions) => {
  const links = definitions.map(createExternalLink).filter(Boolean);
  container.replaceChildren(...links);
  container.hidden = links.length === 0;
  return links.length;
};

const renderOptionalLinks = () => {
  document.querySelectorAll('[data-project-links]').forEach((container) => {
    populateLinks(container, projectLinkDefinitions[container.dataset.projectLinks] || []);
  });

  let profilesVisible = false;
  document.querySelectorAll('[data-profile-links]').forEach((container) => {
    profilesVisible = populateLinks(container, profileLinkDefinitions) > 0 || profilesVisible;
  });
  document.querySelectorAll('[data-profile-group]').forEach((group) => {
    group.hidden = !profilesVisible;
  });
};

const getInitialLanguage = () => {
  try {
    const stored = localStorage.getItem('preferred-language');
    if (stored === 'en' || stored === 'fr') return stored;
  } catch (_) {}
  return (navigator.language || '').toLowerCase().startsWith('fr') ? 'fr' : 'en';
};

const updateMenuLabel = () => {
  const isOpen = menuButton.getAttribute('aria-expanded') === 'true';
  menuLabel.textContent = t(isOpen ? 'closeNavigation' : 'openNavigation');
};

const clearFormFeedback = () => {
  document.querySelectorAll('[data-error-for]').forEach((element) => { element.textContent = ''; });
  contactForm.querySelectorAll('[aria-invalid="true"]').forEach((element) => element.removeAttribute('aria-invalid'));
  formStatus.textContent = '';
  formStatus.className = 'form-status';
};

const applyLanguage = (language, persist = false) => {
  currentLanguage = language === 'fr' ? 'fr' : 'en';
  document.documentElement.lang = currentLanguage;
  document.title = t('metaTitle');
  metaDescription.setAttribute('content', t('metaDescription'));

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    element.innerHTML = t(element.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    element.setAttribute('alt', t(element.dataset.i18nAlt));
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === currentLanguage;
    button.setAttribute('aria-pressed', String(isActive));
    button.classList.toggle('active', isActive);
  });

  formLanguage.value = currentLanguage;
  updateMenuLabel();
  clearFormFeedback();

  if (persist) {
    try { localStorage.setItem('preferred-language', currentLanguage); } catch (_) {}
  }
};

const updateHeader = () => header.classList.toggle('scrolled', window.scrollY > 20);
